-- ==============================================================
-- Настройка мониторов: Строгий Full HD (1920x1080) для всех
-- ==============================================================

-- Экран ноутбука (Full HD)
hl.monitor({
    output = "eDP-1",
    mode = "1920x1080",
    position = "0x0",
    scale = 1,
})

-- Телевизор (Full HD, расположен сверху)
hl.monitor({
    output = "HDMI-A-1",
    mode = "1920x1080",
    position = "auto-up",
    scale = 1,
})

-- Универсальное правило для любых внешних мониторов
hl.monitor({
    output = "",
    mode = "1920x1080",
    position = "auto-up",
    scale = 1,
})
